"""One-off generator for `evals/t10/corpus.yaml`.

Deterministically cycles through the cross product of every `Theme` x
`Emotion` x `Imagery` x `Tone` value from
`personal_voice_msg.discovery.inspiration`, in fixed nested-loop order
(theme outermost, tone innermost), and takes the first 100 combinations in
that order. Re-running this script reproduces the exact same
`corpus.yaml` byte-for-byte, since enum member order and the loop nesting
are both fixed in source.

Kept in the repo (not deleted after use) purely for reproducibility of the
frozen, committed `corpus.yaml` -- it is not part of the qualification run
itself and is not imported by `provider.py` or `promptfooconfig.yaml`.

Usage:
    uv run python evals/t10/generate_corpus.py > evals/t10/corpus.yaml
"""

from __future__ import annotations

import sys

from personal_voice_msg.discovery.inspiration import Emotion, Imagery, Theme, Tone

ROW_COUNT = 100


def build_rows() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for theme in Theme:
        for emotion in Emotion:
            for imagery in Imagery:
                for tone in Tone:
                    rows.append(
                        {
                            "theme": theme.value,
                            "emotion": emotion.value,
                            "imagery": imagery.value,
                            "tone": tone.value,
                        }
                    )
    return rows[:ROW_COUNT]


def render_yaml(rows: list[dict[str, str]]) -> str:
    lines = [
        "# Generated by evals/t10/generate_corpus.py -- do not hand-edit.",
        "# 100 InspirationCard {theme, emotion, imagery, tone} combinations,",
        "# taken from the first 100 entries of the fixed nested-loop cross",
        "# product (theme outermost, tone innermost) over",
        "# personal_voice_msg.discovery.inspiration's Theme/Emotion/Imagery/Tone.",
    ]
    for row in rows:
        lines.append("- vars:")
        lines.append(f"    theme: {row['theme']}")
        lines.append(f"    emotion: {row['emotion']}")
        lines.append(f"    imagery: {row['imagery']}")
        lines.append(f"    tone: {row['tone']}")
    return "\n".join(lines) + "\n"


def main() -> None:
    rows = build_rows()
    assert len(rows) == ROW_COUNT, f"expected {ROW_COUNT} rows, got {len(rows)}"
    sys.stdout.write(render_yaml(rows))


if __name__ == "__main__":
    main()
